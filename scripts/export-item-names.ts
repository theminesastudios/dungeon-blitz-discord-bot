/**
 * Regenerates `src/data/itemNames.ts` from the game's `MountTypes.xml` and `DyeTypes.json`.
 *
 * The save stores mounts and dyes by numeric id; only the game knows what mount 81 is called.
 * The bot also asks the game server for these names at runtime (`gameContent.ts`), but when
 * that read is unavailable every grant and pack line would fall back to `Mount #81`, so a
 * generated snapshot is kept here as the baseline the live read refreshes.
 *
 *   npx tsx scripts/export-item-names.ts <path to MountTypes.xml> <path to DyeTypes.json>
 *
 * In the game repository they live at `src/client/content/xml/MountTypes.xml` and
 * `src/server/data/DyeTypes.json`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const [mountSource, dyeSource] = process.argv.slice(2);
if (!mountSource || !dyeSource) {
	console.error("Usage: npx tsx scripts/export-item-names.ts <MountTypes.xml> <DyeTypes.json>");
	process.exit(1);
}

function decodeXml(value: string): string {
	return value
		.replace(/&lt;/g, "<")
		.replace(/&gt;/g, ">")
		.replace(/&quot;/g, '"')
		.replace(/&apos;/g, "'")
		.replace(/&amp;/g, "&");
}

function tag(block: string, name: string): string {
	const match = block.match(new RegExp(`<${name}>([\\s\\S]*?)</${name}>`));
	return match ? decodeXml(match[1]).trim() : "";
}

const mounts = [...readFileSync(mountSource, "utf8").matchAll(/<MountType\b[\s\S]*?<\/MountType>/g)]
	.map((match) => ({ id: Number(tag(match[0], "MountID")), name: tag(match[0], "DisplayName") }))
	.filter((mount) => Number.isSafeInteger(mount.id) && mount.id > 0 && mount.name)
	.sort((a, b) => a.id - b.id);

type RawDye = { name?: string };
const rawDyes = JSON.parse(readFileSync(dyeSource, "utf8")) as Record<string, RawDye>;
const dyes = Object.entries(rawDyes)
	.map(([id, dye]) => ({ id: Number(id), name: String(dye?.name ?? "").trim() }))
	.filter((dye) => Number.isSafeInteger(dye.id) && dye.id > 0 && dye.name)
	.sort((a, b) => a.id - b.id);

const table = (entries: Array<{ id: number; name: string }>) =>
	entries.map((entry) => `\t${entry.id}: ${JSON.stringify(entry.name)},`).join("\n");

const target = fileURLToPath(new URL("../src/data/itemNames.ts", import.meta.url));
writeFileSync(
	target,
	`// Generated by scripts/export-item-names.ts from the game's MountTypes.xml and DyeTypes.json. Do not edit by hand.\n\n` +
		`/** Mount display names, keyed by the game's mount id. */\n` +
		`export const MOUNT_NAME_SNAPSHOT: Record<number, string> = {\n${table(mounts)}\n};\n\n` +
		`/** Dye display names, keyed by the game's dye id. */\n` +
		`export const DYE_NAME_SNAPSHOT: Record<number, string> = {\n${table(dyes)}\n};\n`,
);
console.log(`Wrote ${mounts.length} mounts and ${dyes.length} dyes to ${target}`);
