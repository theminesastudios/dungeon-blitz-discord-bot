/**
 * Uploads the game icons in `assets/emojis/*.png` as this application's emojis and writes
 * their ids to `src/ui/emojiIds.ts`, which `src/ui/emojis.ts` renders from.
 *
 *   npx tsx scripts/sync-emojis.ts            # upload what is missing, rewrite emojiIds.ts
 *   npx tsx scripts/sync-emojis.ts --dry-run  # only report what would change
 *
 * Needs DISCORD_APPLICATION_ID and DISCORD_BOT_TOKEN (read from .env / the shell). An emoji
 * that already exists under the same name is kept, not re-uploaded: replace one by deleting
 * it in the Developer Portal first. The PNGs are exported from the client SWFs with FFDec —
 * `assets/emojis/SOURCES.md` records which symbol each one came from.
 */
import dotenv from "dotenv";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

dotenv.config();

const applicationId = process.env.DISCORD_APPLICATION_ID?.trim();
const token = process.env.DISCORD_BOT_TOKEN?.trim();
if (!applicationId || !token) {
	console.error("DISCORD_APPLICATION_ID and DISCORD_BOT_TOKEN are required.");
	process.exit(1);
}
const dryRun = process.argv.includes("--dry-run");

const assetsDir = fileURLToPath(new URL("../assets/emojis/", import.meta.url));
const target = fileURLToPath(new URL("../src/ui/emojiIds.ts", import.meta.url));
const api = `https://discord.com/api/v10/applications/${applicationId}/emojis`;
const headers = { Authorization: `Bot ${token}`, "Content-Type": "application/json" };

type ApplicationEmoji = { id: string; name: string };

async function listEmojis(): Promise<ApplicationEmoji[]> {
	const response = await fetch(api, { headers });
	if (!response.ok) throw new Error(`List failed [${response.status}] ${await response.text()}`);
	const body = (await response.json()) as { items?: ApplicationEmoji[] };
	return body.items ?? [];
}

async function upload(name: string, file: string): Promise<ApplicationEmoji> {
	const image = `data:image/png;base64,${readFileSync(file).toString("base64")}`;
	const response = await fetch(api, { method: "POST", headers, body: JSON.stringify({ name, image }) });
	if (!response.ok) throw new Error(`Upload of ${name} failed [${response.status}] ${await response.text()}`);
	return (await response.json()) as ApplicationEmoji;
}

const files = readdirSync(assetsDir)
	.filter((file) => /^[a-z0-9_]{2,32}\.png$/.test(file))
	.sort();
const existing = new Map((await listEmojis()).map((item) => [item.name, item.id]));
const ids: Record<string, string> = {};

for (const file of files) {
	const name = file.slice(0, -".png".length);
	const known = existing.get(name);
	if (known) {
		ids[name] = known;
		continue;
	}
	if (dryRun) {
		console.log(`would upload ${name}`);
		continue;
	}
	const created = await upload(name, `${assetsDir}${file}`);
	ids[name] = created.id;
	console.log(`uploaded ${name} -> ${created.id}`);
}

if (!dryRun) {
	const body = Object.entries(ids)
		.map(([name, id]) => `\t${name}: "${id}",`)
		.join("\n");
	writeFileSync(
		target,
		"// Generated by scripts/sync-emojis.ts. Do not edit by hand:\n" +
			"// it maps each application emoji name to the id Discord assigned when it was uploaded.\n" +
			`export const EMOJI_IDS: Record<string, string> = {\n${body}\n};\n`,
	);
	console.log(`Wrote ${Object.keys(ids).length} emoji ids to ${target}`);
}
