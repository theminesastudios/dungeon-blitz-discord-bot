/**
 * Regenerates `src/data/abilities.ts` from the game's ability data.
 *
 * The save stores a character's abilities as `{ abilityID, rank }`; only the game knows that
 * ability 3 is "Triple Strike" and tops out at rank 10. `/admin profile` shows staff every
 * ability a character has learned and how far it is upgraded, so a generated snapshot is kept
 * here instead of a live game-server read.
 *
 *   npx tsx scripts/export-abilities.ts <AbilityTypes.json> <PlayerPowerTypes.xml>
 *
 * In the game repository the files live at `src/server/data/AbilityTypes.json` (ids, classes
 * and one row per rank) and `src/client/content/xml/PlayerPowerTypes.xml` (the names players
 * see — `AbilityTypes` only has internal ones like `QuickStrike`).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

type RawAbility = {
	AbilityName?: string;
	AbilityID?: string;
	Class?: string;
	Rank?: string;
};

const [abilitySource, powerSource] = process.argv.slice(2);
if (!abilitySource || !powerSource) {
	console.error("Usage: npx tsx scripts/export-abilities.ts <AbilityTypes.json> <PlayerPowerTypes.xml>");
	process.exit(1);
}

const displayNames = new Map<string, string>();
const powers = readFileSync(powerSource, "utf8");
for (const match of powers.matchAll(/<Power PowerName="([^"]+)">([\s\S]*?)<\/Power>/g)) {
	const displayName = /<DisplayName>([^<]*)<\/DisplayName>/.exec(match[2])?.[1]?.trim();
	if (displayName && displayName !== "----" && !displayNames.has(match[1])) {
		displayNames.set(match[1], displayName);
	}
}

const raw = JSON.parse(readFileSync(abilitySource, "utf8")) as RawAbility[] | Record<string, RawAbility>;
const abilities = new Map<number, { name: string; className: string; maxRank: number }>();
for (const row of Array.isArray(raw) ? raw : Object.values(raw)) {
	const id = Number(row.AbilityID);
	const rank = Number(row.Rank) || 0;
	const known = abilities.get(id);
	if (known) {
		known.maxRank = Math.max(known.maxRank, rank);
		continue;
	}
	const internalName = String(row.AbilityName ?? "").trim();
	if (!Number.isSafeInteger(id) || id <= 0 || !internalName) continue;
	abilities.set(id, {
		// Fall back to splitting the internal name ("SteelCyclone" -> "Steel Cyclone").
		name: displayNames.get(internalName) ?? internalName.replace(/([a-z])([A-Z])/g, "$1 $2"),
		className: String(row.Class ?? "").trim(),
		maxRank: rank,
	});
}

const lines = [...abilities.entries()]
	.sort(([a], [b]) => a - b)
	.map(([id, ability]) => `\t${id}: ${JSON.stringify(ability)},`);

const output = `// Generated by scripts/export-abilities.ts from the game's AbilityTypes.json and PlayerPowerTypes.xml. Do not edit by hand.
export type AbilityInfo = { name: string; className: string; maxRank: number };

export const ABILITIES: Record<number, AbilityInfo> = {
${lines.join("\n")}
};
`;

const target = fileURLToPath(new URL("../src/data/abilities.ts", import.meta.url));
writeFileSync(target, output);
console.log(`Wrote ${abilities.size} abilities to ${target}`);
