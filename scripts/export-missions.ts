/**
 * Regenerates `src/data/missions.ts` from the game's `MissionTypes.json`.
 *
 * The save stores missions by numeric id; only the game knows what mission 6 is called.
 * `/player` needs the name and tracker text to show a player's current quest, and quests
 * change rarely, so a generated snapshot is kept here instead of a live game-server read.
 *
 *   npx tsx scripts/export-missions.ts <path to MissionTypes.json>
 *
 * The file lives at `src/server/data/MissionTypes.json` in the game repository.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

type RawMission = {
	MissionID?: string;
	DisplayName?: string;
	TrackerText?: string;
	TrackerReturn?: string;
	Priority?: string;
	MissionLevel?: string;
};

const source = process.argv[2];
if (!source) {
	console.error("Usage: npx tsx scripts/export-missions.ts <MissionTypes.json>");
	process.exit(1);
}

const raw = JSON.parse(readFileSync(source, "utf8")) as RawMission[] | Record<string, RawMission>;
const missions = (Array.isArray(raw) ? raw : Object.values(raw))
	.map((mission) => ({
		id: Number(mission.MissionID),
		name: String(mission.DisplayName ?? "").trim(),
		tracker: String(mission.TrackerText ?? "").trim(),
		turnIn: String(mission.TrackerReturn ?? "").trim(),
		story: mission.Priority === "Story",
		level: Number(mission.MissionLevel) || 0,
	}))
	.filter((mission) => Number.isSafeInteger(mission.id) && mission.id > 0 && mission.name)
	.sort((a, b) => a.id - b.id);

const body = missions
	.map(
		(mission) =>
			`\t${mission.id}: ${JSON.stringify({
				name: mission.name,
				tracker: mission.tracker,
				turnIn: mission.turnIn,
				story: mission.story,
				level: mission.level,
			})},`,
	)
	.join("\n");

const target = fileURLToPath(new URL("../src/data/missions.ts", import.meta.url));
writeFileSync(
	target,
	`// Generated by scripts/export-missions.ts from the game's MissionTypes.json. Do not edit by hand.\n` +
		`export type MissionInfo = { name: string; tracker: string; turnIn: string; story: boolean; level: number };\n\n` +
		`export const MISSIONS: Record<number, MissionInfo> = {\n${body}\n};\n`,
);
console.log(`Wrote ${missions.length} missions to ${target}`);
